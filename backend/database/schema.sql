CREATE TABLE IF NOT EXISTS products (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(200) NOT NULL, description TEXT NULL, category VARCHAR(120) NULL,
 price DECIMAL(10,2) NOT NULL, original_price DECIMAL(10,2) NULL, stock INT UNSIGNED NOT NULL DEFAULT 0, sku VARCHAR(80) NULL UNIQUE,
 sizes JSON NULL, colors JSON NULL, status ENUM('active','inactive') NOT NULL DEFAULT 'active', featured BOOLEAN NOT NULL DEFAULT FALSE,
 image_url VARCHAR(500) NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 INDEX idx_products_status_category(status,category)
);
CREATE TABLE IF NOT EXISTS orders (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NULL, customer_name VARCHAR(120) NOT NULL,
 customer_email VARCHAR(190) NULL, shipping_address JSON NULL, subtotal DECIMAL(10,2) NOT NULL DEFAULT 0, total DECIMAL(10,2) NOT NULL,
 payment_method VARCHAR(40) NULL, coupon_code VARCHAR(60) NULL, payment_status ENUM('pending','paid','failed','refunded','partially_refunded') NOT NULL DEFAULT 'pending',
 status ENUM('pending','confirmed','processing','shipped','out_for_delivery','delivered','cancelled','returned') NOT NULL DEFAULT 'pending',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE SET NULL, INDEX idx_orders_created(created_at)
);
CREATE TABLE IF NOT EXISTS order_items (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, order_id BIGINT UNSIGNED NOT NULL, product_id BIGINT UNSIGNED NULL,
 product_name VARCHAR(200) NOT NULL, quantity INT UNSIGNED NOT NULL, unit_price DECIMAL(10,2) NOT NULL,
 size VARCHAR(20) NULL, color VARCHAR(40) NULL, FOREIGN KEY(order_id) REFERENCES orders(id) ON DELETE CASCADE,
 FOREIGN KEY(product_id) REFERENCES products(id) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS payments (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, order_id BIGINT UNSIGNED NULL, user_id BIGINT UNSIGNED NULL,
 provider VARCHAR(40) NOT NULL, transaction_id VARCHAR(160) NULL, provider_order_id VARCHAR(160) NULL,
 amount DECIMAL(10,2) NOT NULL, status ENUM('created','authorized','paid','failed','refunded','partially_refunded') NOT NULL DEFAULT 'created',
 refund_id VARCHAR(160) NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(order_id) REFERENCES orders(id) ON DELETE SET NULL, FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS returns_requests (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, order_id BIGINT UNSIGNED NOT NULL, user_id BIGINT UNSIGNED NULL,
 customer_name VARCHAR(120) NOT NULL, reason TEXT NOT NULL, status ENUM('pending','approved','rejected','refunded') NOT NULL DEFAULT 'pending',
 refund_amount DECIMAL(10,2) NULL, admin_note TEXT NULL, refund_id VARCHAR(160) NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY(order_id) REFERENCES orders(id) ON DELETE CASCADE, FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS coupons (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, code VARCHAR(60) NOT NULL UNIQUE, discount_type ENUM('percentage','fixed') NOT NULL DEFAULT 'percentage',
 discount_value DECIMAL(10,2) NOT NULL, minimum_order DECIMAL(10,2) NOT NULL DEFAULT 0, maximum_discount DECIMAL(10,2) NULL,
 starts_at DATETIME NULL, expires_at DATETIME NULL, usage_limit INT UNSIGNED NULL, usage_count INT UNSIGNED NOT NULL DEFAULT 0,
 active BOOLEAN NOT NULL DEFAULT TRUE, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS banners (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, title VARCHAR(180) NOT NULL, subtitle VARCHAR(240) NULL,
 image_url VARCHAR(500) NULL, button_text VARCHAR(80) NULL, redirect_url VARCHAR(500) NULL, position INT NOT NULL DEFAULT 0,
 active BOOLEAN NOT NULL DEFAULT TRUE, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS reviews (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NULL, product_id BIGINT UNSIGNED NULL,
 customer_name VARCHAR(120) NOT NULL, product_name VARCHAR(200) NULL, rating TINYINT UNSIGNED NOT NULL,
 description TEXT NULL, status ENUM('pending','published','hidden','reported') NOT NULL DEFAULT 'pending',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE SET NULL,
 FOREIGN KEY(product_id) REFERENCES products(id) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS notifications (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, type VARCHAR(40) NOT NULL, title VARCHAR(180) NOT NULL, body TEXT NULL,
 read_at DATETIME NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS store_settings (
 setting_key VARCHAR(100) PRIMARY KEY, value TEXT NOT NULL, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
